//! `KeyboardEvent.code` to Snow's universal scancodes (the Apple Extended Keyboard's, ADB).
//! Snow translates them to the keyboard the model has; the Plus's M0110 lacks some (arrows,
//! keypad, function keys), and those are dropped there.
//!
//! The table follows Snow's own frontend (frontend_egui/src/keymap.rs). The modifiers are laid
//! out for a PC keyboard: Alt, next to the space bar, is Command, as on a Mac's; Ctrl is Option
//! (the Plus has no Control key); the Windows/Meta key is Command too.

pub fn scancode(code: &str) -> Option<u8> {
    Some(match code {
        "Escape" => 0x35,
        "F1" => 0x7A,
        "F2" => 0x78,
        "F3" => 0x63,
        "F4" => 0x76,
        "F5" => 0x60,
        "F6" => 0x61,
        "F7" => 0x62,
        "F8" => 0x64,
        "F9" => 0x65,
        "F10" => 0x6D,
        "F11" => 0x67,
        "F12" => 0x6F,

        "Backquote" => 0x32,
        "Digit1" => 0x12,
        "Digit2" => 0x13,
        "Digit3" => 0x14,
        "Digit4" => 0x15,
        "Digit5" => 0x17,
        "Digit6" => 0x16,
        "Digit7" => 0x1A,
        "Digit8" => 0x1C,
        "Digit9" => 0x19,
        "Digit0" => 0x1D,
        "Minus" => 0x1B,
        "Equal" => 0x18,
        "Backspace" => 0x33,

        "Insert" => 0x72,
        "Home" => 0x73,
        "PageUp" => 0x74,
        "Delete" => 0x75,
        "End" => 0x77,
        "PageDown" => 0x79,

        "Tab" => 0x30,
        "KeyQ" => 0x0C,
        "KeyW" => 0x0D,
        "KeyE" => 0x0E,
        "KeyR" => 0x0F,
        "KeyT" => 0x11,
        "KeyY" => 0x10,
        "KeyU" => 0x20,
        "KeyI" => 0x22,
        "KeyO" => 0x1F,
        "KeyP" => 0x23,
        "BracketLeft" => 0x21,
        "BracketRight" => 0x1E,
        "Backslash" => 0x2A,

        "CapsLock" => 0x39,
        "KeyA" => 0x00,
        "KeyS" => 0x01,
        "KeyD" => 0x02,
        "KeyF" => 0x03,
        "KeyG" => 0x05,
        "KeyH" => 0x04,
        "KeyJ" => 0x26,
        "KeyK" => 0x28,
        "KeyL" => 0x25,
        "Semicolon" => 0x29,
        "Quote" => 0x27,
        "Enter" => 0x24,

        "ShiftLeft" => 0x38,
        "KeyZ" => 0x06,
        "KeyX" => 0x07,
        "KeyC" => 0x08,
        "KeyV" => 0x09,
        "KeyB" => 0x0B,
        "KeyN" => 0x2D,
        "KeyM" => 0x2E,
        "Comma" => 0x2B,
        "Period" => 0x2F,
        "Slash" => 0x2C,
        "ShiftRight" => 0x7B,
        "IntlBackslash" => 0x0A,

        "Space" => 0x31,
        // Command
        "AltLeft" | "AltRight" | "MetaLeft" | "MetaRight" | "OSLeft" | "OSRight" => 0x37,
        // Option
        "ControlLeft" | "ControlRight" => 0x3A,

        "ArrowUp" => 0x3E,
        "ArrowLeft" => 0x3B,
        "ArrowDown" => 0x3D,
        "ArrowRight" => 0x3C,

        "NumLock" => 0x47,
        "NumpadEqual" => 0x51,
        "NumpadDivide" => 0x4B,
        "NumpadMultiply" => 0x43,
        "NumpadSubtract" => 0x4E,
        "NumpadAdd" => 0x45,
        "NumpadEnter" => 0x4C,
        "NumpadDecimal" => 0x41,
        "Numpad0" => 0x52,
        "Numpad1" => 0x53,
        "Numpad2" => 0x54,
        "Numpad3" => 0x55,
        "Numpad4" => 0x56,
        "Numpad5" => 0x57,
        "Numpad6" => 0x58,
        "Numpad7" => 0x59,
        "Numpad8" => 0x5B,
        "Numpad9" => 0x5C,
        _ => return None,
    })
}
