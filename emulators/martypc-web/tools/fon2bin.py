#!/usr/bin/env python3
"""Convert a Windows .FON (NE resource, FNT v2/v3 bitmap font) into the glyph layout
MartyPC's core embeds: row-major, 256 bytes per scanline (byte N of a row is glyph N),
`rows` scanlines, glyph pixels in the top 8 bits (MSB = leftmost).

usage: fon2bin.py FONT.FON ROWS OUT.bin
"""
import struct, sys

def fnt_resources(data):
    ne = struct.unpack_from('<I', data, 0x3C)[0]
    assert data[ne:ne + 2] == b'NE', 'not an NE executable'
    rtab = ne + struct.unpack_from('<H', data, ne + 0x24)[0]
    shift = struct.unpack_from('<H', data, rtab)[0]
    p = rtab + 2
    while True:
        tid, count = struct.unpack_from('<HH', data, p)
        if tid == 0:
            break
        p += 8
        for _ in range(count):
            off, length = struct.unpack_from('<HH', data, p)
            if tid == 0x8008:  # RT_FONT
                yield data[off << shift:(off << shift) + (length << shift)]
            p += 12

def glyphs(fnt):
    version = struct.unpack_from('<H', fnt, 0)[0]
    height = struct.unpack_from('<H', fnt, 0x58)[0]
    first, last = fnt[0x5F], fnt[0x60]
    table = 0x76 if version == 0x200 else 0x94
    entry = 4 if version == 0x200 else 6
    out = {}
    for i in range(last - first + 1):
        if version == 0x200:
            w, off = struct.unpack_from('<HH', fnt, table + i * entry)
        else:
            w, off = struct.unpack_from('<HI', fnt, table + i * entry)
        # Bitmaps are stored column-of-bytes: all rows of the first 8 pixels, then the next 8.
        rows = []
        for r in range(height):
            bits = 0
            for col in range((w + 7) // 8):
                bits = (bits << 8) | fnt[off + col * height + r]
            rows.append((bits, (w + 7) // 8 * 8))
        out[first + i] = (w, rows)
    return height, out

def main():
    path, nrows, dest = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    fnt = next(fnt_resources(open(path, 'rb').read()))
    height, g = glyphs(fnt)
    buf = bytearray(256 * nrows)
    for code in range(256):
        w, rows = g[code]
        for r in range(min(height, nrows)):
            bits, span = rows[r]
            # Keep the leftmost 8 pixels (MDA's 9th column is generated by hardware).
            buf[r * 256 + code] = (bits >> (span - 8)) & 0xFF
    open(dest, 'wb').write(bytes(buf))
    print(f'{path}: {len(g)} glyphs, {w}x{height} -> {dest} ({len(buf)} bytes)')

if __name__ == '__main__':
    main()
